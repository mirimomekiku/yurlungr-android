#!/usr/bin/env bash
# Shared setup helpers. Source from Bash, then call setup_init with the log path.
set -o pipefail

setup_init() {
  if [ -z "${PREFIX:-}" ] || [ -z "${HOME:-}" ] || [ ! -x "$PREFIX/bin/bash" ]; then
    printf 'Setup needs the installed Yurlungr Linux environment. Open System checks first.\n' >&2
    exit 64
  fi
  # What packages add for login shells (JAVA_HOME from the JDK…), so the checks see it too.
  local _f _nounset=0
  case $- in *u*) _nounset=1; set +u ;; esac
  # Not written for `set -u`: one reading an unset variable would end the setup silently.
  for _f in "$PREFIX"/etc/profile.d/*.sh; do [ -r "$_f" ] && . "$_f" >/dev/null 2>&1 </dev/null; done
  [ "$_nounset" = 1 ] && set -u
  local tool
  for tool in apt-get tee timeout flock; do
    if ! command -v "$tool" >/dev/null 2>&1; then
      printf 'Setup cannot start: missing %s. Repair the Linux environment in System checks.\n' "$tool" >&2
      exit 69
    fi
  done
  LOG="$1"
  # Names the status file System checks reads, e.g. agents-setup.status.
  SETUP_NAME=$(basename "$LOG" .log)
  STATUS_DIR="$PREFIX/var/lib/yurlungr/setup"
  FAILED=()
  FINISH_REPORTED=0
  CLEANUP=()
  SIGKILLED=0
  mkdir -p "$PREFIX/var/lock" "$PREFIX/tmp" "${LOG%/*}" "$STATUS_DIR" || exit 73
  # One lock for all installers. The kernel releases it even after a crash or reboot.
  exec 9>"$PREFIX/var/lock/yurlungr-setup.lock" || exit 73
  if ! flock -n 9; then
    # Before any trap: this run must not overwrite the status of the one that is running.
    printf 'Another setup is already running. Wait for it to finish, or end its terminal process, then retry.\n' >&2
    exit 75
  fi
  # From here every way out records a status. Closing the terminal tab sends SIGHUP; without its
  # own trap the EXIT trap would see the last command's status (often 0) and record success.
  # Steps run in their own process groups (see with_timeout), listed here so these traps end them.
  STEP_GROUPS="$PREFIX/tmp/yurlungr-setup-$$.groups"
  : > "$STEP_GROUPS" 2>/dev/null || STEP_GROUPS=/dev/null
  trap 'stop_steps; exit 129' HUP
  trap 'stop_steps; exit 130' INT
  trap 'stop_steps; exit 143' TERM
  trap 'status=$?; stop_steps; cleanup_paths; [ "$STEP_GROUPS" = /dev/null ] || rm -f "$STEP_GROUPS"; write_status "$status"; if [ "$status" -ne 0 ] && [ "$FINISH_REPORTED" -eq 0 ]; then printf "\nSetup stopped (exit %s). Details: %s. Fix the error above and rerun setup.\n" "$status" "$LOG" >&2; fi' EXIT
  # "Running" until it ends: a run killed outright (SIGKILL, the app or phone dying) skips every
  # trap, and must then read as interrupted, not as whatever the previous run recorded.
  write_status -1
  # Package lists and version checks, generated by the app from the list System checks uses.
  local manifest="$PREFIX/libexec/yurlungr/toolchain.sh"
  if [ ! -r "$manifest" ] || ! source "$manifest"; then
    printf 'Setup cannot start: %s is missing. Open the Yurlungr app once so it can write it, then retry.\n' "$manifest" >&2
    exit 69
  fi
  if [ -f "$LOG" ] && ! mv -f "$LOG" "$LOG.previous"; then
    printf 'Cannot preserve the previous setup log: %s\n' "$LOG" >&2
    exit 73
  fi
  if ! : > "$LOG"; then
    printf 'Cannot write setup log: %s. Check free storage and retry.\n' "$LOG" >&2
    exit 73
  fi
  COLS=$(stty size 2>/dev/null | cut -d' ' -f2) || COLS=80
  case "$COLS" in ''|*[!0-9]*) COLS=80 ;; esac
  if [ "$COLS" -lt 20 ] || [ "$COLS" -gt 300 ]; then COLS=80; fi
  export DEBIAN_FRONTEND=noninteractive
  # Wait (up to 2 min) for a `pkg` the user is running in a terminal instead of failing at once.
  # A stalled mirror gives up instead of holding the setup lock forever.
  APT_LOCK=(-o DPkg::Lock::Timeout=120 -o Acquire::http::Timeout=60 -o Acquire::https::Timeout=60 -o Acquire::Retries=2)
  # confold: keep config files the user edited (bash.bashrc, nanorc, sources.list) when a package updates.
  APT_OPTS=(-y "${APT_LOCK[@]}" -o Dpkg::Options::=--force-confdef -o Dpkg::Options::=--force-confold)
}

# How this run ended, for System checks: exit code (-1 while running), its pid, log, time, and
# each failed step.
write_status() {
  local code=$1 tmp="$STATUS_DIR/$SETUP_NAME.status.tmp" item
  {
    printf 'exit\t%s\npid\t%s\nlog\t%s\nfinished\t%s\n' "$code" "$$" "$LOG" "$(date +%s)"
    for item in "${FAILED[@]}"; do printf 'failed\t%s\n' "$item"; done
  } > "$tmp" 2>/dev/null && mv -f "$tmp" "$STATUS_DIR/$SETUP_NAME.status" 2>/dev/null
  return 0
}

# Stops early when there clearly isn't room: half-installed packages are worse than none.
require_space() { # MB
  local free_kb
  free_kb=$(df -Pk "$PREFIX" 2>/dev/null | awk 'NR==2 {print $4}')
  case "$free_kb" in ''|*[!0-9]*) return 0 ;; esac
  if [ "$free_kb" -lt $(( $1 * 1024 )) ]; then
    printf 'Not enough free storage: %s MB free, about %s MB needed. Free some space and retry.\n' "$(( free_kb / 1024 ))" "$1" >&2
    FAILED+=("free storage")
    exit 74
  fi
}

# Repairs an interrupted dpkg run and refreshes the package index. Returns 1 when the index
# can't be downloaded: installing from stale or unreachable mirrors would only fail per package.
apt_prepare() {
  if [ -n "$(dpkg --audit 2>/dev/null)" ]; then
    # Answer config-file questions up front: a prompt would wait forever on a line that's never shown.
    run_logged with_timeout 1800 dpkg --force-confdef --force-confold --configure -a
    # A killed `apt-get install` can leave packages unpacked without their dependencies, which
    # `dpkg --configure -a` can't finish: apt completes them (or removes what can't be).
    if [ -n "$(dpkg --audit 2>/dev/null)" ]; then
      run_logged with_timeout 1800 apt-get -f install "${APT_OPTS[@]}"
    fi
    if [ -z "$(dpkg --audit 2>/dev/null)" ]; then
      ok "repaired an interrupted package install"
    else
      bad "package repair (dpkg --configure -a, apt-get -f install)"
    fi
  fi
  if run_logged with_timeout 600 apt-get "${APT_LOCK[@]}" update; then
    return 0
  fi
  bad "package index update"
  printf '  Package lists could not be downloaded. Check the network, or choose another mirror with: termux-change-repo\n' >&2
  return 1
}

install_pkgs() {
  local p
  for p in "$@"; do
    run_logged with_timeout 1800 apt-get install "${APT_OPTS[@]}" "$p" && ok "$p" || bad "$p"
  done
}

# Runs "name<TAB>command" entries from toolchain.sh through check. Optional tools (agents
# installed one by one from the app) are checked only when present, like System checks does.
run_checks() {
  local entry name only
  # Declared even if an older toolchain.sh didn't define it (an empty map: everything is checked).
  declare -gA YURLUNGR_ONLY_IF
  for entry in "$@"; do
    name=${entry%%$'\t'*}
    only=${YURLUNGR_ONLY_IF[$name]:-}
    if [ -n "$only" ] && [ ! -e "$PREFIX/$only" ]; then
      printf '\n[%s skipped: not installed]\n' "$name" >> "$LOG"
      continue
    fi
    check "$name" "${entry#*$'\t'}"
  done
}

step() { printf '\n\033[1;36m==> %s\033[0m\n' "$*"; }
ok() { printf '\033[32m  ✓ %s\033[0m\n' "$*"; }
bad() { printf '\033[31m  ✗ %s\033[0m\n' "$*"; FAILED+=("$*"); }
# Something the user should know that isn't a failure: on stderr, so it shows even from inside
# $(...), and in the log.
warn() {
  printf '\033[33m  ! %s\033[0m\n' "$*" >&2
  printf '\n[warning] %s\n' "$*" >> "${LOG:-/dev/null}" 2>/dev/null
  return 0
}

# Removes a scratch folder the setup made when it ends, however it ends: Ctrl-C, a closed tab and
# errors all go through the EXIT trap.
cleanup_on_exit() { CLEANUP+=("$1"); }
cleanup_paths() {
  local p
  for p in "${CLEANUP[@]+"${CLEANUP[@]}"}"; do [ -n "$p" ] && rm -rf -- "$p" 2>/dev/null; done
  CLEANUP=()
  return 0
}

# Runs a command with its output logged and shown one line at a time. Its stdin is /dev/null:
# anything that asks a question fails at once instead of waiting on a prompt nobody can see.
run_logged() {
  "$@" 9>&- </dev/null 2>&1 | tee -a "$LOG" | while IFS= read -r line || [ -n "$line" ]; do
    line=${line##*$'\r'}
    if [ -n "$line" ]; then printf '\r\033[K\033[2m  %s\033[0m' "${line:0:$((COLS - 3))}"; fi
  done
  local -a statuses=("${PIPESTATUS[@]}")
  printf '\r\033[K'
  if [ "${statuses[1]}" -ne 0 ]; then
    printf 'Cannot save setup output to %s. Check free storage.\n' "$LOG" >&2
    return "${statuses[1]}"
  fi
  # 137: killed by signal 9, usually Android's limit on background processes (see setup_finish).
  if [ "${statuses[0]}" -eq 137 ]; then SIGKILLED=1; fi
  if [ "${statuses[0]}" -ne 0 ]; then return "${statuses[0]}"; fi
  return "${statuses[2]}"
}

# Limits a step to SECS, children included: timeout runs it in a process group of its own and
# signals the whole group (with --foreground it signalled only the first process, so a pipeline,
# npm's postinstall scripts or a Gradle daemon outlived it and the step hung). -k kills what
# ignores the polite signal. Ctrl-C and closing the tab reach the setup's own group, not this one,
# so the group is recorded for the traps to end (stop_steps).
with_timeout() { # SECS command...
  local secs=$1 pid rc g rest=
  shift
  timeout -k 10 "$secs" "$@" &
  pid=$!
  printf '%s\n' "$pid" >> "${STEP_GROUPS:-/dev/null}" 2>/dev/null
  wait "$pid"
  rc=$?
  # Done: unlisted, so stop_steps can't signal a later process group that reuses the pid.
  if [ -n "${STEP_GROUPS:-}" ] && [ "$STEP_GROUPS" != /dev/null ] && [ -r "$STEP_GROUPS" ]; then
    while IFS= read -r g; do [ "$g" = "$pid" ] || rest+="$g"$'\n'; done < "$STEP_GROUPS"
    printf '%s' "$rest" > "$STEP_GROUPS" 2>/dev/null
  fi
  return "$rc"
}

# Ends every step group still running (on Ctrl-C, a closed tab, or exit).
stop_steps() {
  local g
  [ -n "${STEP_GROUPS:-}" ] && [ -r "$STEP_GROUPS" ] || return 0
  while IFS= read -r g; do
    case "$g" in ''|*[!0-9]*) continue ;; esac
    kill -TERM -- "-$g" 2>/dev/null
  done < "$STEP_GROUPS"
  return 0
}

check() {
  local output status
  if output=$(with_timeout 60 bash -o pipefail -c "$2" 9>&- </dev/null 2>&1); then status=0; else status=$?; fi
  if ! printf '\n[%s exit=%s]\n%s\n' "$1" "$status" "$output" >> "$LOG"; then
    bad "$1 (cannot write $LOG)"
    return 1
  fi
  if [ "$status" -eq 0 ] && [ -n "$output" ]; then
    ok "$1: ${output%%$'\n'*}"
  else
    bad "$1 (exit $status; see $LOG)"
  fi
}

setup_finish() {
  if [ "${#FAILED[@]}" -ne 0 ]; then
    printf '\n\033[1;31mFailed: %s\033[0m (details: %s)\n' "${FAILED[*]}" "$LOG" >&2
    FINISH_REPORTED=1 # the EXIT trap needn't say it again
    # A step was killed by signal 9: exit 137 lets System checks and the terminal say Android did it.
    if [ "${SIGKILLED:-0}" = 1 ]; then exit 137; fi
    exit 1
  fi
  printf '\n\033[1;32m%s\033[0m\n' "$1"
}
